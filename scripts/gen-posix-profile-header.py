#!/usr/bin/env python3
"""Generate include/sys/posix-profile-trim.h from the profile registry.

The build-selectable POSIX profiles are advertised by
letting <unistd.h> define every option macro as it always has, then including
this generated header, which `#undef`s each standard option NOT in the active
build profile (`full - active`, from posix_profile.POSIX_PROFILES).  The active
profile is selected by the Kconfig `choice`, surfaced to the preprocessor as
`-DCONFIG_POSIX_PROFILE_{MINIMAL,REALTIME,LKL}=1` (mk/toolchain.mk).  `full` --
the default -- defines no such macro, so nothing is trimmed and the advertised
surface is byte-identical to a build without profiles.

Run with no args to (re)write the header; `--check` verifies the checked-in
header matches the registry and exits non-zero on drift.

SPDX-License-Identifier: Apache-2.0
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADER = ROOT / "include" / "sys" / "posix-profile-trim.h"
sys.path.insert(0, str(ROOT / "scripts"))
from posix_profile import OPTION_REQUIREMENTS, POSIX_PROFILES  # noqa: E402

# The profiles smaller than `full`, each paired with its Kconfig guard.  `full`
# is the default and trims nothing, so it needs no section.
_TRIMMED = (
    ("CONFIG_POSIX_PROFILE_MINIMAL", "minimal"),
    ("CONFIG_POSIX_PROFILE_REALTIME", "realtime"),
    ("CONFIG_POSIX_PROFILE_LKL", "lkl"),
)


def render():
    # Only real option-group macros are profile-gated.  Capability/behavior
    # values (_POSIX_VERSION, _POSIX_VDISABLE, _POSIX_NO_TRUNC, the _PC_* _IO
    # caps, _POSIX_SAVED_IDS, _POSIX_MONOTONIC_CLOCK, ...) are baseline and must
    # never be trimmed, so restrict the trimmable set to OPTION_REQUIREMENTS.
    trimmable = frozenset(OPTION_REQUIREMENTS) & POSIX_PROFILES["full"]
    out = [
        "/*",
        " * GENERATED by scripts/gen-posix-profile-header.py -- do not edit.",
        " *",
        " * Trims the advertised POSIX option macros to the active build profile.",
        " * <unistd.h> defines every option macro, then includes this header, which",
        " * #undefs each standard option outside the active profile. The `full` profile",
        " * (the default) trims nothing. See scripts/posix_profile.POSIX_PROFILES.",
        " *",
        " * SPDX-License-Identifier: Apache-2.0",
        " */",
        "",
        "#ifndef _SYS_POSIX_PROFILE_TRIM_H",
        "#define _SYS_POSIX_PROFILE_TRIM_H",
        "",
    ]
    for i, (guard, name) in enumerate(_TRIMMED):
        drop = sorted(trimmable - POSIX_PROFILES[name])
        out.append(f"{'#if' if i == 0 else '#elif'} defined({guard})")
        out.append(f"/* {name}: drop the {len(drop)} option(s) outside it */")
        out.extend(f"#undef {opt}" for opt in drop)
    out.append("#endif /* profile guard */")
    out.append("")
    out.append("#endif /* _SYS_POSIX_PROFILE_TRIM_H */")
    return "\n".join(out) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            print(f"{HEADER.relative_to(ROOT)} is stale; run "
                  "scripts/gen-posix-profile-header.py", file=sys.stderr)
            return 1
        print("posix-profile-trim.h: ok")
        return 0
    HEADER.write_text(text, encoding="utf-8")
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
