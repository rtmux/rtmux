"""Regenerate tests/host/sh-quote-cases.h from a reference POSIX shell.

Each case is a command line of words. The reference shell (dash) runs
`set -- LINE; printf '%d' $#; for a; do printf '<%s>' "$a"; done` with the variables below set, in an empty
directory, and the fields it prints are checked in as literals, so the host
test and the guest suite need no reference shell. Usage:

    gen-sh-quote-cases.py [--check] [OUTPUT]

It also writes tests/userland/sh-posix/quote-cases.dat, two lines per case (the
line, then its fields), which the guest suite runs through the shell under test.
--check compares both files with a fresh run and exits 1 on any difference.
"""
import os
import re
import subprocess
import sys
import tempfile

SHELL = os.environ.get("REF_SH", "dash")
MAX_CASES = 260
VARS = "A='x y' B= C=' a  b ' D='p*q'"

CASES = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "sh-quote-cases.txt")



def cases():
    seen = []
    with open(CASES) as f:
        for line in f.read().split("\n"):
            if line and line not in seen:
                seen.append(line)
    return seen


def run_ref(line):
    # A line the reference shell rejects (an unterminated quote) has no fields.
    nbs = len(line) - len(line.rstrip("\\"))
    if nbs % 2:
        return None  # a trailing backslash would join the next script line
    probe = "%s\nset -- %s\n" % (VARS, line)
    if subprocess.run([SHELL, "-n", "-c", probe], capture_output=True).returncode:
        return None
    script = probe + "printf '%d' $#; for a; do printf '<%s>' \"$a\"; done\n"
    with tempfile.TemporaryDirectory() as d:
        r = subprocess.run([SHELL, "-c", script], cwd=d, capture_output=True,
                           text=True, timeout=10)
    if r.returncode != 0:
        return None
    return r.stdout


# What the host test can emulate: $A $B $C $D $Z, ${NAME}, and $(echo ...) or
# `echo ...` with nothing but words in it. The guest suite runs every case.
SIMPLE = re.compile(r"\$\{[A-Za-z_]+\}|\$[A-Za-z_]|\$\(echo[^;|&()$`]*\)|"
                    r"`echo[^;|&()$`\\]*`")


def host_ok(line):
    return not re.search(r"\$[({0-9#?!*@'\"-]|`|\$$", SIMPLE.sub("", line))


def cstr(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def render():
    rows = []
    for line in cases():
        if "\n" in line:
            continue
        got = run_ref(line)
        if got is None:
            continue
        rows.append((line, got))
    if len(rows) > MAX_CASES:  # an even, repeatable sample
        rows = [rows[i * len(rows) // MAX_CASES] for i in range(MAX_CASES)]
    text = ["/*",
            " * Quoting cases with the fields a reference POSIX shell (dash) makes of",
            " * them. Generated by gen-sh-quote-cases.py; do not edit by hand.",
            " *",
            " * SPDX-License-Identifier: Apache-2.0",
            " */",
            "",
            "#define SH_QUOTE_VARS \"%s\"" % VARS.replace("'", "'"),
            "",
            "static const struct {",
            "    const char *line;",
            "    const char *fields; /* the count, then each field as <field> */",
            "    int host;           /* 1 if the host test can emulate it */",
            "} sh_quote_cases[] = {"]
    for line, got in rows:
        text.append("    {%s, %s, %d}," % (cstr(line), cstr(got), host_ok(line)))
    text.append("};")
    dat = "".join("%s\n%s\n" % (line, got) for line, got in rows)
    return "\n".join(text) + "\n", dat, len(rows)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    here = os.path.dirname(os.path.abspath(__file__))
    out = args[0] if args else os.path.join(here, "sh-quote-cases.h")
    dat_out = os.path.join(here, "..", "userland", "sh-posix", "quote-cases.dat")
    body, dat, n = render()
    if check:
        if open(out).read() != body or open(dat_out).read() != dat:
            print("the quote case tables differ from %s" % SHELL, file=sys.stderr)
            return 1
        print("sh-quote-cases: %d cases agree with %s" % (n, SHELL))
        return 0
    with open(out, "w") as f:
        f.write(body)
    with open(dat_out, "w") as f:
        f.write(dat)
    print("%d cases" % n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
